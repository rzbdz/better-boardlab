#!/usr/bin/env node
/**
 * Writes the distribution's registries from the modules it has: a module is in this distribution when its directory is
 * in src/modules, so leaving one out is removing its directory. Pluggable modules with a catalog.ts are offered to
 * boardd; a cli.ts adds its `commands`, a ui.tsx its `ui` part of the page. Libraries (no catalog.ts) are neither.
 *
 *   node scripts/modules.mjs           write src/catalog.ts, src/commands.ts and src/uis.ts
 *   node scripts/modules.mjs --check   fail if any of them is not what the modules present would give
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * The registries for a set of modules: `present` the module directories, `has(id, file)` whether one has a file, and
 * `dependencies` architecture.json's module dependencies. Returns {path: text}.
 */
export function registries(present, has, dependencies) {
  // In the order architecture.json declares them, each after what it depends on (boardd orders them by requires anyway;
  // this keeps the command groups and the settings sections in a stable, sensible order).
  const ordered = [], seen = new Set()
  const visit = id => { if (seen.has(id)) return; seen.add(id); for (const dep of dependencies[id] ?? []) if (present.includes(dep)) visit(dep); ordered.push(id) }
  ;[...Object.keys(dependencies).filter(id => present.includes(id)), ...[...present].sort()].forEach(visit)

  const pluggable = ordered.filter(id => has(id, 'catalog.ts'))
  const withCli = pluggable.filter(id => has(id, 'cli.ts')), withUi = pluggable.filter(id => has(id, 'ui.tsx'))
  const name = id => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
  const header = what => `// Generated by scripts/modules.mjs from the modules in src/modules: ${what}. Do not edit; run \`node scripts/modules.mjs\`.\n`
  return {
    'src/catalog.ts': header('the modules boardd can load') +
      "import type { CatalogEntry } from 'boardlab-core/server/catalog.ts'\n" +
      pluggable.map(id => `import { entry as ${name(id)} } from './modules/${id}/catalog.ts'\n`).join('') +
      `\nexport const CATALOG: CatalogEntry[] = [${pluggable.map(name).join(', ')}]\n`,
    'src/commands.ts': header('the command groups the modules add to the CLI') +
      "import type { CommandGroup } from 'boardlab-core/cli/command.ts'\n" +
      withCli.map(id => `import { commands as ${name(id)} } from './modules/${id}/cli.ts'\n`).join('') +
      `\nexport const COMMAND_GROUPS: CommandGroup[] = [${withCli.map(name).join(', ')}]\n`,
    'src/uis.ts': header("the modules' parts of the page") +
      "import type { ModuleUi } from 'boardlab-core/ui/extensions.ts'\n" +
      withUi.map(id => `import { ui as ${name(id)} } from './modules/${id}/ui.tsx'\n`).join('') +
      `\nexport const MODULE_UIS: ModuleUi[] = [${withUi.map(name).join(', ')}]\n`,
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const dependencies = JSON.parse(readFileSync(join(root, 'architecture.json'), 'utf8')).modules?.dependencies ?? {}
  const dir = join(root, 'src/modules')
  const present = readdirSync(dir).filter(name => statSync(join(dir, name)).isDirectory())
  const files = registries(present, (id, file) => existsSync(join(dir, id, file)), dependencies)
  const stale = Object.entries(files).filter(([file, text]) => !existsSync(join(root, file)) || readFileSync(join(root, file), 'utf8') !== text).map(([file]) => file)
  if (process.argv.includes('--check')) {
    if (stale.length) { console.error(`out of date with src/modules: ${stale.join(', ')}; run node scripts/modules.mjs`); process.exit(1) }
  } else for (const file of stale) writeFileSync(join(root, file), files[file])
}
